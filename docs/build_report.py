    doc.add_page_break()
    doc.add_heading("5. GUI Screenshots (continued)",1)
    image(doc,DOCS/"screenshots"/"gui_dashboard_adaptive.jpg",6.6); caption(doc,"Figure 3. Adaptive dashboard, showing intervention events.")
    doc.add_paragraph("This view demonstrates the controller's modeled response; it does not suspend any real host process.")
    doc.add_page_break()

    doc.add_heading("6. Experimental Methodology",1)
    table(doc,["Parameter","Setting"],[["Processes","4"],["Physical frames","16"],["References per process","400"],["References per completed main run","1,600"],["Seeds","42–51 (10 seeds)"],["Workload patterns","5"],["Replacement policies","FIFO, LRU, Clock, Optimal"],["Adaptive modes","4"],["Main TLB-on runs","800"],["Matched TLB-off runs","200"],["Total raw records",len(raw)]])
    table(doc,["Workload","Trace structure"],[["phase locality","Mostly accesses a small region, then shifts by phase."],["uniform random","Random accesses across 64 pages."],["sequential scan","Sequentially scans all 64 pages."],["bursty hot set","Small hot-set bursts interspersed with broad random phases."],["alternating hot sets","Alternates between two disjoint eight-page regions."]])
