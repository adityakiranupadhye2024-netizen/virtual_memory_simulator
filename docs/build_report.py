"""Build a formatted report from the repository's experiment outputs."""
from __future__ import annotations
import csv
from pathlib import Path
from statistics import mean
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.shared import Inches, Pt, RGBColor

ROOT=Path(__file__).resolve().parents[1]
DOCS=ROOT/"docs"
OUT=DOCS/"Virtual_Memory_Management_Project_Report.docx"

def read_csv(path):
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))

def field_page(paragraph):
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    paragraph.alignment=WD_ALIGN_PARAGRAPH.CENTER
    paragraph.add_run("Page ")
    el=OxmlElement("w:fldSimple"); el.set(qn("w:instr"),"PAGE"); paragraph._p.append(el)

def shade(cell, color):
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    shd=OxmlElement("w:shd"); shd.set(qn("w:fill"),color); cell._tc.get_or_add_tcPr().append(shd)

def table(doc, headers, rows):
    t=doc.add_table(rows=1, cols=len(headers)); t.style="Light Shading Accent 1"; t.alignment=WD_TABLE_ALIGNMENT.CENTER
    for i,h in enumerate(headers):
        t.rows[0].cells[i].text=str(h); shade(t.rows[0].cells[i],"24476B")
        for r in t.rows[0].cells[i].paragraphs[0].runs:
            r.bold=True; r.font.color.rgb=RGBColor(255,255,255); r.font.size=Pt(8)
    for row in rows:
        cells=t.add_row().cells
        for i,val in enumerate(row):
            cells[i].text=str(val)
            for p in cells[i].paragraphs:
                p.paragraph_format.space_after=Pt(1)
                for r in p.runs: r.font.size=Pt(8)
            if len(t.rows)%2==0: shade(cells[i],"F1F5F9")
    doc.add_paragraph()

def bullets(doc, items):
    for x in items:
        p=doc.add_paragraph(style="List Bullet"); p.paragraph_format.space_after=Pt(3); p.add_run(x)

def image(doc, path, width=6.65):
    if path.exists():
        p=doc.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.CENTER; p.add_run().add_picture(str(path),width=Inches(width))
    else:
        p=doc.add_paragraph("Visual is generated by the repository build: "+str(path.relative_to(ROOT)))
        p.runs[0].italic=True
def caption(doc, text):
    p=doc.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.space_after=Pt(6)
    r=p.add_run(text); r.italic=True; r.font.size=Pt(8); r.font.color.rgb=RGBColor(95,115,135)

