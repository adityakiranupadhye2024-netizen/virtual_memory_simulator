    doc.styles["Normal"].paragraph_format.space_after=Pt(4)
    h=sec.header.paragraphs[0]; h.text="OPERATING SYSTEMS LAB  •  VIRTUAL MEMORY SIMULATOR"; h.alignment=WD_ALIGN_PARAGRAPH.RIGHT
