    table(doc,["TLB measure","Result"],[["Mean table accesses, TLB on",f"{mean(on):,.1f}"],["Mean table accesses, TLB off",f"{mean(off):,.1f}"],["Reduction in table accesses",f"{100*(1-mean(on)/mean(off)):.1f}%"],["Page-fault mismatches in matched pairs",f"{mismatches} / {len(offrows)}"]])
    image(doc,DOCS/"figures"/"tlb_effect.png",5.7); caption(doc,"Figure 6. Translation-table access overhead, TLB enabled vs disabled.")
