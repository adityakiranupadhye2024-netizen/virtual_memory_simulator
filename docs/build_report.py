    reduction=100*(b-c)/b if b else 0
    on=[int(r["page_table_accesses"]) for r in raw if r["control_mode"]=="none" and r["tlb_enabled"].lower()=="true"]
    off=[int(r["page_table_accesses"]) for r in raw if r["control_mode"]=="none_tlb_off_check"]
