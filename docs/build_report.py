    doc.add_heading("3. Virtual-Memory Model",1)
    doc.add_heading("Address format and translation",2)
    doc.add_paragraph("The modeled page size is 256 bytes; the offset is the low eight bits. The 64 virtual pages use two 3-bit page-table indices, with eight entries at each level, giving a virtual address range of 0 through 16,383.")
    table(doc,["Stage","Action","Metric"],[["TLB lookup","Lookup cached translation by (process, VPN).","TLB hits and misses."],["Page-table walk","Check first- and second-level entries.","Page-table accesses."],["Page fault","Select a frame allocated to process; evict if occupied; map VPN.","Faults and replacements."],["Physical address","Combine frame number and page offset.","Address shown in event log."]])
    doc.add_heading("Replacement policies",2)
    table(doc,["Policy","Summary"],[["FIFO","Evict the page loaded earliest."],["LRU","Evict the least recently used resident page."],["Clock","Use reference bits to implement a second-chance scan."],["Optimal*","Evict the resident page whose next use is farthest away."]])
    doc.add_paragraph("*Optimal uses knowledge of future generated references and is only a theoretical oracle comparison, not an implementable online policy.")
    doc.add_page_break()

    doc.add_heading("4. Thrashing Detection and Adaptive Control",1)
    doc.add_paragraph("A recent-reference window estimates each process's working set. A trend heuristic estimates possible near-term growth in demand. Pressure compares active working-set demand to frame capacity. Thrashing detection combines a rolling page-fault ratio and an overload condition. These are hand-set rules, not a trained machine-learning model.")
    table(doc,["Mode","Redistribution","Suspension","Interpretation"],[["none","Off","Off","Baseline."],["redistribution_only","On","Off","Isolates effects of frame allocation changes."],["suspension_only","Off","On","Suspended process retains its allocation, allowing suspension effect to be isolated."],["combined","On","On","Suspension and reallocation can coordinate."]])
    doc.add_paragraph("Suspension-only page-fault counts therefore remain equal to baseline in this implementation. In combined mode, frame redistribution can transfer the suspended process's frames to active processes. The outcome is workload-dependent.")
    doc.add_heading("Dashboard",2)
