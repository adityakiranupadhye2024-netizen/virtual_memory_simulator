    table(doc,["Module","Responsibility"],[["vm_simulator/core.py","TLB, page tables, physical frames, replacement, workloads, monitoring, and adaptive controls."],["vm_simulator/gui.py","Tkinter dashboard, charts, process/frame tables, event log, address inspector, CSV export."],["benchmark.py","Multi-seed experiment, ablations, confidence-interval summaries, paired effect analysis, TLB comparisons."],["docs/generate_figures.py","Rebuild figures from the experiment CSVs and render the architecture diagram."]])
