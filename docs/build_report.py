    p=doc.add_paragraph(); p.paragraph_format.space_before=Pt(78); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    r=p.add_run("PREDICTIVE AND ADAPTIVE\nVIRTUAL MEMORY MANAGEMENT"); r.bold=True; r.font.size=Pt(27); r.font.color.rgb=RGBColor(22,58,91)
    p=doc.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    r=p.add_run("with Intelligent Thrashing Prevention"); r.font.size=Pt(17); r.font.color.rgb=RGBColor(37,109,133)
    p=doc.add_paragraph(); p.paragraph_format.space_before=Pt(26); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.add_run("OPERATING SYSTEMS LAB PROJECT REPORT").bold=True
    p=doc.add_paragraph(); p.paragraph_format.space_before=Pt(36); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.add_run("Submitted by\nAditya Kiran Upadhye\nAman Singh Sachan\nAditya Jain")
    p=doc.add_paragraph(); p.paragraph_format.space_before=Pt(32); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.add_run("A reproducible simulation of address translation,\npage replacement, thrashing detection, and adaptive control.")
    doc.add_page_break()

    doc.add_heading("1. Executive Summary",1)
    doc.add_paragraph("This project implements an educational virtual-memory simulator. It models address translation through a translation lookaside buffer (TLB) and a two-level page table, simulates page faults and replacement, estimates working-set pressure, detects thrashing using rule-based thresholds, and demonstrates adaptive frame redistribution and temporary process suspension.")
    doc.add_paragraph(f"The committed experiment has {len(raw)} rows across five synthetic workload patterns, ten seeds, four replacement policies, four adaptive-control modes, and matched TLB checks. Under LRU, combined adaptation reduced pooled mean faults from {b:,.1f} to {c:,.1f} ({reduction:.1f}% by ratio of means). The mean paired reduction is {float(lru_pair['mean_percent_reduction']):.1f}%. These are simulator results, not measurements from a real operating system.")
    doc.add_heading("Objectives",2)
    bullets(doc,["Demonstrate a full virtual-address translation path with TLB and hierarchical page tables.","Compare FIFO, LRU, Clock, and Optimal page replacement on repeatable reference streams.","Estimate working-set pressure and detect simulated thrashing.","Evaluate frame redistribution and process suspension independently and together.","Publish run-level CSV output, summaries, figures, tests, and a reproducible report."])
    doc.add_heading("Scope",2)
    doc.add_paragraph("The simulator does not inspect or modify host OS memory, kernel page tables, live CPU usage, or real running processes. CPU utilization, pressure, and process suspension shown in the dashboard are simulated proxies.")
